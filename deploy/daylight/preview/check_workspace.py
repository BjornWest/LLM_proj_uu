"""Verify the site-first design prototype, using only local sample pages and records."""
import argparse
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT=Path(__file__).resolve().parents[3]
libs=ROOT/'.local/system-libs/usr/lib/x86_64-linux-gnu'
if libs.is_dir():os.environ['LD_LIBRARY_PATH']=str(libs)+':'+os.environ.get('LD_LIBRARY_PATH','')
parser=argparse.ArgumentParser();parser.add_argument('--origin',default='http://localhost:8892');args=parser.parse_args()
origin=args.origin.rstrip('/');output=ROOT/'.local/ux-preview-images';output.mkdir(parents=True,exist_ok=True)
checks=[]
def check(name,condition=True):
    assert condition,name
    checks.append(name);print('PASS',name,flush=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1600,'height':1050})
    errors=[];writes=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.on('request',lambda r:writes.append(r.url) if r.method!='GET' else None)
    page.goto(origin+'/workspace')
    frame=page.frame_locator('iframe[data-site=campus]')
    expect(frame.get_by_role('heading',name='Reserve a study room')).to_be_visible()
    expect(page.locator('#explore-view')).to_be_visible()
    check('Entry opens the interactive website with the agent sidebar')

    # Capture actual local Campus states for illustrative replay viewports.
    page.locator('iframe[data-site=campus]').screenshot(path=str(output/'campus-0.png'))
    frame.locator('#room-building').select_option('Ångström')
    frame.locator('#room-people').select_option('3')
    page.locator('iframe[data-site=campus]').screenshot(path=str(output/'campus-1.png'))
    frame.locator('[data-room]').first.click()
    page.locator('iframe[data-site=campus]').screenshot(path=str(output/'campus-2.png'))
    frame.get_by_role('button',name='Confirm booking').click()
    expect(frame.locator('.room-receipt')).to_have_count(1)
    page.locator('iframe[data-site=campus]').screenshot(path=str(output/'campus-3.png'))
    page.locator('#reset-page').click()
    expect(frame.locator('.room-receipt')).to_have_count(0)
    frame.get_by_role('link',name='Shop',exact=True).click()
    expect(frame.get_by_role('heading',name='Ready for your next idea.')).to_be_visible()
    frame.get_by_role('button',name='Add A5 notebook',exact=True).click()
    check('Manual site navigation and page controls remain usable',page.evaluate('window.demoWorld.state.cart.notebook')==1)

    page.locator('#question').fill('Find a room for three people')
    page.locator('#send-question').click()
    expect(page.locator('#send-question')).to_be_enabled(timeout=10000)
    expect(frame.locator('#room-people')).to_have_value('3')
    expect(page.locator('#conversation')).to_contain_text('I have not made a reservation')
    check('Ask sidebar operates the currently explored page with a labeled scripted reply',page.evaluate('window.demoWorld.state.bookings.length')==0)

    page.locator('#research-tab').click()
    expect(page.locator('#research-view')).to_be_visible()
    check('Site tasks and replay history stay scoped to Campus',page.locator('#task-cards .task-card').count()==3 and page.locator('#replay-rows tr:not([data-site=campus])').count()==0)
    check('Replay titles distinguish Task from Ask and show recorded grades',page.locator('#replay-rows .run-kind.task').count()>0 and page.locator('#replay-rows .run-kind.ask').count()>0 and page.locator('#replay-rows .grade.partial').count()==1 and page.locator('#replay-rows .grade.failed').count()==1)
    page.screenshot(path=str(ROOT/'.local/ux-sites-tasks.png'),full_page=True)

    page.locator('[data-run=sample-campus-partial] .replay-action').click()
    expect(page.locator('#review-grade')).to_have_text('Partial')
    expect(page.locator('#grade-note')).to_contain_text('two of three')
    before=page.evaluate('JSON.stringify(window.demoWorld.state)')
    page.locator('#review-play').click()
    expect(page.locator('#review-position')).to_have_text('4 / 4',timeout=7000)
    check('Replay is view-only and does not change the interactive site',page.evaluate('JSON.stringify(window.demoWorld.state)')==before and page.locator('#review-view iframe').count()==0)
    page.locator('#explore-tab').click()
    expect(frame.locator('#room-people')).to_have_value('3')
    check('Returning to Explore preserves the manual browser state')
    page.locator('#toggle-agent').click();expect(page.locator('#agent-sidebar')).to_be_hidden()
    page.locator('#toggle-agent').click();expect(page.locator('#agent-sidebar')).to_be_visible()
    check('Extension sidebar can be hidden and reopened')

    page.locator('[data-site=fieldnotes].site-choice').click()
    books=page.frame_locator('iframe[data-site=fieldnotes]')
    expect(books.get_by_role('heading',name='Find something worth noticing.')).to_be_visible()
    books.locator('.choose').nth(1).click()
    expect(books.locator('#result')).to_contain_text('The Art of Wandering')
    check('Second site has its own clickable pages and independent conversation',page.locator('#conversation .message').count()==0)
    for step in range(4):
        capture=browser.new_page(viewport={'width':1100,'height':720})
        capture.goto(origin+f'/preview/site?site=sample-bookshop&step={step}')
        capture.screenshot(path=str(output/f'sample-bookshop-{step}.png'));capture.close()
    page.screenshot(path=str(ROOT/'.local/ux-sites-explore.png'),full_page=True)
    page.locator('#question').fill('Show me the second book');page.locator('#send-question').click()
    expect(page.locator('#conversation')).to_contain_text('149 SEK')
    page.locator('#sidebar-tasks').click()
    check('Bookshop tasks and replays exclude Campus',page.locator('#replay-rows tr:not([data-site=fieldnotes])').count()==0)
    page.locator('[data-task=fieldnotes-find]').click()
    expect(page.locator('#task-dialog')).to_be_visible()
    expect(page.locator('#dialog-goal')).to_contain_text('Do not buy anything')
    page.locator('#try-task').click()
    expect(page.locator('#review-grade')).to_have_text('In progress')
    expect(page.locator('#review-grade')).to_have_text('Succeeded',timeout=8000)
    check('Task details show the exact goal and launch a labeled local sample attempt')

    page.locator('#all-replays-link').click()
    expect(page).to_have_url(origin+'/workspace/replays')
    expect(page.locator('#global-view')).to_be_visible()
    check('All traces and replays has a separate URL and contains both sites',page.locator('#global-rows tr[data-site=campus]').count()>0 and page.locator('#global-rows tr[data-site=fieldnotes]').count()>0)
    page.locator('#global-site').select_option('fieldnotes');page.locator('#global-kind').select_option('task');page.locator('#global-grade').select_option('partial')
    expect(page.locator('#global-rows tr')).to_have_count(1)
    check('Global site, activity and grade filters combine precisely',page.locator('#global-rows .run-title').inner_text()=='TaskCompare three paperbacks')
    page.locator('#global-collection').select_option('Campus demos')
    expect(page.locator('#global-empty')).to_be_visible()
    page.locator('#clear-filters').click()
    page.locator('#global-search').fill('sample-campus-unknown')
    expect(page.locator('#global-rows tr')).to_have_count(1)
    expect(page.locator('#global-rows .grade')).to_have_text('Unknown')
    check('Collection/search filtering and missing grades retain clear empty or unknown states')
    page.locator('#clear-filters').click()
    page.screenshot(path=str(ROOT/'.local/ux-sites-global.png'),full_page=True)
    page.locator('#global-rows [data-run=sample-books-ask] .replay-action').click()
    expect(page.locator('#review-grade')).to_have_text('Not graded')
    expect(page.locator('#recorded-site')).to_contain_text('Fieldnotes')
    page.locator('#back-to-research').click();expect(page.locator('#global-view')).to_be_visible()
    page.reload();expect(page.locator('#global-view')).to_be_visible()
    check('Global recording inspection returns to the global library and the URL reloads correctly')

    for width in [390,720,1000]:
        page.set_viewport_size({'width':width,'height':844})
        check(f'Global layout fits {width}px',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(ROOT/'.local/ux-sites-global-mobile.png'),full_page=True)
    page.locator('[data-site=fieldnotes].site-choice').click()
    expect(page.locator('#explore-view')).to_be_visible()
    check('Mobile Explore fits the viewport',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    page.screenshot(path=str(ROOT/'.local/ux-sites-explore-mobile.png'),full_page=True)
    check('No model/API mutations or browser JavaScript errors',not writes and not errors)
    browser.close()
print(f'{len(checks)} local design checks passed. Screenshots: .local/ux-sites-*.png')
